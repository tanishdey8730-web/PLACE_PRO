export const MOCKS_BY_ID = new Map(MOCK_CATALOG.map((m) => [m.id, m]));

export function mockQuestionCount(mock: MockDefinition): number {
  return mock.blueprint.reduce((sum, slice) => sum + slice.count, 0);
}

export function mocksByGroup(group: MockGroup): MockDefinition[] {
  return MOCK_CATALOG.filter((m) => m.group === group);
}
